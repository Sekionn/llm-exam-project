package dk.ek.gruppe_i.llm_project.service;

import dk.ek.gruppe_i.llm_project.config.AiDeploymentProperties;
import org.springframework.ai.embedding.EmbeddingModel;
import org.springframework.core.io.ClassPathResource;
import org.springframework.core.io.Resource;
import org.springframework.core.io.support.PathMatchingResourcePatternResolver;
import org.springframework.stereotype.Component;
import org.springframework.util.StreamUtils;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Minimal RAG: markdown files in src/main/resources/rag are split into sections, embedded with the local Ollama
 * embedding model, and the sections most similar to the query are retrieved with cosine similarity.
 * No database, nothing is stored on disk. Chunks are embedded on first use, so the application can start
 * without Ollama running.
 * <p>
 * Two sources: the Smart City data description used by {@code /ask} (HOUSING_CAPACITY) and the apartment
 * material generated by the EDA notebook ({@code apartment-*.md}) used by {@code /housing-capacity}.
 */
@Component
public class HousingKnowledgeBase {

    static final String RESOURCE = "rag/housing-data-context.md";
    static final String APARTMENT_PATTERN = "classpath:rag/apartment-*.md";

    private final EmbeddingModel embeddingModel;
    private final AiDeploymentProperties properties;
    private final Map<String, List<Chunk>> chunksBySource = new HashMap<>();

    public HousingKnowledgeBase(EmbeddingModel embeddingModel, AiDeploymentProperties properties) {
        this.embeddingModel = embeddingModel;
        this.properties = properties;
    }

    /** Smart City data description, best match first (used by /ask). */
    public List<String> retrieve(String query) {
        return retrieveFrom(RESOURCE, query);
    }

    /** Apartment rules, reference figures, data profile and worked examples from the EDA notebook. */
    public List<String> retrieveApartmentRules(String query) {
        return retrieveFrom(APARTMENT_PATTERN, query);
    }

    private List<String> retrieveFrom(String source, String query) {
        List<Chunk> all = loadChunks(source);
        float[] queryVector = embeddingModel.embed(query);
        return all.stream()
                .sorted(Comparator.comparingDouble((Chunk chunk) -> cosine(queryVector, chunk.vector())).reversed())
                .limit(Math.max(1, properties.getRagTopK()))
                .map(Chunk::text)
                .toList();
    }

    private synchronized List<Chunk> loadChunks(String source) {
        List<Chunk> cached = chunksBySource.get(source);
        if (cached == null) {
            List<String> texts = new ArrayList<>();
            for (String markdown : readSource(source)) {
                texts.addAll(split(markdown));
            }
            if (texts.isEmpty()) {
                throw new IllegalStateException("No RAG material found for " + source);
            }
            List<float[]> vectors = embeddingModel.embed(texts);
            List<Chunk> loaded = new ArrayList<>();
            for (int i = 0; i < texts.size(); i++) {
                loaded.add(new Chunk(texts.get(i), vectors.get(i)));
            }
            cached = List.copyOf(loaded);
            chunksBySource.put(source, cached);
        }
        return cached;
    }

    private List<String> readSource(String source) {
        try {
            Resource[] resources = source.contains("*")
                    ? new PathMatchingResourcePatternResolver().getResources(source)
                    : new Resource[]{new ClassPathResource(source)};
            Arrays.sort(resources, Comparator.comparing(Resource::getFilename, Comparator.nullsFirst(Comparator.naturalOrder())));
            List<String> texts = new ArrayList<>();
            for (Resource resource : resources) {
                try (InputStream in = resource.getInputStream()) {
                    texts.add(StreamUtils.copyToString(in, StandardCharsets.UTF_8));
                }
            }
            return texts;
        } catch (IOException ex) {
            throw new IllegalStateException("Could not read RAG source " + source, ex);
        }
    }

    /** Splits markdown into one chunk per "## " section. Text before the first section is its own chunk. */
    static List<String> split(String markdown) {
        List<String> result = new ArrayList<>();
        StringBuilder current = new StringBuilder();
        for (String line : markdown.split("\\R")) {
            if (line.startsWith("## ") && !current.toString().isBlank()) {
                result.add(current.toString().trim());
                current.setLength(0);
            }
            current.append(line).append('\n');
        }
        if (!current.toString().isBlank()) {
            result.add(current.toString().trim());
        }
        return result;
    }

    static double cosine(float[] a, float[] b) {
        double dot = 0;
        double normA = 0;
        double normB = 0;
        for (int i = 0; i < a.length && i < b.length; i++) {
            dot += a[i] * b[i];
            normA += a[i] * a[i];
            normB += b[i] * b[i];
        }
        return normA == 0 || normB == 0 ? 0 : dot / (Math.sqrt(normA) * Math.sqrt(normB));
    }

    private record Chunk(String text, float[] vector) {
    }
}
